function assertRecord(value, location) {
  if (value === null || typeof value !== "object" || Array.isArray(value)) {
    throw new TypeError(`${location} must be a mapping`);
  }
  return value;
}

function schemaNameFromReference(reference) {
  const prefix = "#/components/schemas/";
  return typeof reference === "string" && reference.startsWith(prefix)
    ? reference.slice(prefix.length)
    : undefined;
}

function responseNameFromReference(reference) {
  const prefix = "#/components/responses/";
  return typeof reference === "string" && reference.startsWith(prefix)
    ? reference.slice(prefix.length)
    : undefined;
}

export function dereferenceResponse(document, value) {
  let response = assertRecord(value, "operation response");
  const references = new Set();
  while (response.$ref !== undefined) {
    const reference = response.$ref;
    const name = responseNameFromReference(reference);
    if (name === undefined) {
      throw new TypeError(`Unsupported response reference ${JSON.stringify(reference)}`);
    }
    if (references.has(reference)) {
      throw new TypeError(`Circular response reference ${JSON.stringify(reference)}`);
    }
    references.add(reference);
    response = assertRecord(
      assertRecord(assertRecord(document.components, "components").responses, "responses")[name],
      name,
    );
  }
  return response;
}

function operationParameters(pathItem, operation) {
  return [
    ...(Array.isArray(pathItem.parameters) ? pathItem.parameters : []),
    ...(Array.isArray(operation.parameters) ? operation.parameters : []),
  ];
}

function dereferenceParameter(document, value) {
  const parameter = assertRecord(value, "operation parameter");
  if (parameter.$ref === undefined) return parameter;
  if (parameter.$ref === IDEMPOTENCY_PARAMETER) {
    return assertRecord(
      assertRecord(assertRecord(document.components, "components").parameters, "parameters")
        .IdempotencyKey,
      "IdempotencyKey",
    );
  }
  throw new TypeError(`Unsupported parameter reference ${JSON.stringify(parameter.$ref)}`);
}

function schemaAtBodyPath(document, operation, path) {
  const body = assertRecord(operation.requestBody, "requestBody");
  const content = assertRecord(body.content, "requestBody.content");
  let schema = assertRecord(
    assertRecord(content[JSON_CONTENT_TYPE], JSON_CONTENT_TYPE).schema,
    "body schema",
  );
  if (schema.$ref !== undefined) {
    const name = schemaNameFromReference(schema.$ref);
    if (name === undefined) throw new TypeError(`Unsupported body reference ${schema.$ref}`);
    schema = assertRecord(
      assertRecord(assertRecord(document.components, "components").schemas, "schemas")[name],
      name,
    );
  }
  for (const segment of path.split(".")) {
    const properties = assertRecord(schema.properties, `properties containing ${path}`);
    schema = assertRecord(properties[segment], `body field ${path}`);
    if (schema.$ref !== undefined) {
      const name = schemaNameFromReference(schema.$ref);
      if (name === undefined)
        throw new TypeError(`Unsupported body field reference ${schema.$ref}`);
      schema = assertRecord(
        assertRecord(assertRecord(document.components, "components").schemas, "schemas")[name],
        name,
      );
    }
  }
  return schema;
}

export function validateOperationProfile(document, profile) {
  const operations = collectOperations(document);
  const operationIds = operations.map(({ operationId }) => operationId);
  const expected = new Set(operationIds);
  const mappings = assertRecord(profile, "operation profile").operations;
  const iterators = profile.iterators;
  if (!Array.isArray(mappings) || !Array.isArray(iterators)) {
    throw new TypeError("Operation profile mappings must be arrays");
  }
  if (mappings.length !== EXPECTED_OPERATION_COUNT) {
    throw new TypeError(
      `Operation profile must contain ${EXPECTED_OPERATION_COUNT} primary mappings`,
    );
  }
  if (iterators.length !== EXPECTED_ITERATOR_COUNT) {
    throw new TypeError(
      `Operation profile must contain ${EXPECTED_ITERATOR_COUNT} iterator mappings`,
    );
  }

  const mappedIds = mappings.map((value) => assertRecord(value, "profile operation").operationId);
  const duplicateIds = mappedIds.filter((value, index) => mappedIds.indexOf(value) !== index);
  const missing = operationIds.filter((operationId) => !mappedIds.includes(operationId));
  const extra = mappedIds.filter(
    (operationId) => typeof operationId !== "string" || !expected.has(operationId),
  );
  if (duplicateIds.length > 0 || missing.length > 0 || extra.length > 0) {
    throw new TypeError(
      `Operation profile parity failure: duplicates=${JSON.stringify([...new Set(duplicateIds)])}, missing=${JSON.stringify(missing)}, extra=${JSON.stringify(extra)}`,
    );
  }

  const aliases = [...mappings, ...iterators].map((value) => {
    const mapping = assertRecord(value, "profile mapping");
    if (typeof mapping.facade !== "string" || typeof mapping.method !== "string") {
      throw new TypeError("Every profile mapping must name a facade and method");
    }
    return `${mapping.facade}.${mapping.method}`;
  });
  const duplicateAliases = aliases.filter((value, index) => aliases.indexOf(value) !== index);
  if (duplicateAliases.length > 0) {
    throw new TypeError(`Duplicate facade mappings: ${[...new Set(duplicateAliases)].join(", ")}`);
  }

  for (const value of iterators) {
    const mapping = assertRecord(value, "iterator mapping");
    if (typeof mapping.operationId !== "string" || !expected.has(mapping.operationId)) {
      throw new TypeError(
        `Iterator references unknown operation ${JSON.stringify(mapping.operationId)}`,
      );
    }
  }
  if (Object.hasOwn(profile, "digest") || Object.hasOwn(profile, "sha256")) {
    throw new TypeError("Operation profile must not contain a self-digest");
  }
}

export function validateAuthorizationRegistry(document, registry = AUTHORIZATION_REGISTRY) {
  const operations = new Map(
    collectOperations(document).map((entry) => [entry.operationId, entry]),
  );
  const kindSemantics = {
    body_domain: { quantifier: "one" },
    query_domain_required_for_scoped: { condition: "scoped_role_requires_filter" },
    existing_and_replacement_domain: { quantifier: "every" },
    all_body_domains: {
      quantifier: "every",
      condition: "global_scope_requires_global_role",
    },
    existing_and_new_domains: {
      quantifier: "every",
      transition: "global_scope_requires_global_role",
    },
    comma_separated_query_domains: { quantifier: "every" },
    authorized_domain_filter: {},
    existing_resource_domains: {},
  };
  const resourceSchemas = {
    message: "MessageSummary",
    route: "Route",
    webhook: "Webhook",
    smtp_credential: "SMTPCredential",
  };

  for (const [operationId, value] of Object.entries(registry)) {
    const entry = operations.get(operationId);
    if (entry === undefined) throw new TypeError(`Authorization rule references ${operationId}`);
    const rule = assertRecord(value, `authorization rule ${operationId}`);
    const expectedSemantics = kindSemantics[rule.kind];
    if (expectedSemantics === undefined) {
      throw new TypeError(
        `${operationId} has unknown authorization rule ${JSON.stringify(rule.kind)}`,
      );
    }
    for (const [key, expected] of Object.entries(expectedSemantics)) {
      if (rule[key] !== expected) {
        throw new TypeError(
          `${operationId} authorization ${key} must be ${JSON.stringify(expected)}`,
        );
      }
    }
    if (
      !["one", "at_least_one"].includes(rule.quantifier) &&
      ["authorized_domain_filter", "existing_resource_domains"].includes(rule.kind)
    ) {
      throw new TypeError(`${operationId} authorization quantifier must describe domain matching`);
    }
    if (
      typeof rule.summary !== "string" ||
      rule.summary.length === 0 ||
      rule.summary.trim() !== rule.summary
    ) {
      throw new TypeError(`${operationId} authorization summary must be a stable non-empty string`);
    }
    const roles = assertRecord(rule.roles, `${operationId} authorization roles`);
    if (typeof roles.global !== "string" || typeof roles.domain !== "string") {
      throw new TypeError(`${operationId} authorization roles must name global and domain roles`);
    }
    const pathItem = assertRecord(assertRecord(document.paths, "paths")[entry.path], entry.path);
    const parameterNames = new Map(
      operationParameters(pathItem, entry.operation)
        .map((parameter) => dereferenceParameter(document, parameter))
        .filter((parameter) => typeof parameter.name === "string")
        .map((parameter) => [parameter.name, parameter.in]),
    );

    if (
      typeof rule.queryParameter === "string" &&
      parameterNames.get(rule.queryParameter) !== "query"
    ) {
      throw new TypeError(`${operationId} has no ${rule.queryParameter} query parameter`);
    }
    if (
      typeof rule.resourceIdParameter === "string" &&
      parameterNames.get(rule.resourceIdParameter) !== "path"
    ) {
      throw new TypeError(`${operationId} has no ${rule.resourceIdParameter} path parameter`);
    }
    for (const key of ["bodyPath", "replacementBodyPath", "newBodyPath", "scopeBodyPath"]) {
      if (typeof rule[key] === "string") schemaAtBodyPath(document, entry.operation, rule[key]);
    }
    const resourceSchemaName = resourceSchemas[rule.resource];
    for (const key of ["existingPath", "resourceDomainPath"]) {
      if (typeof rule[key] !== "string") continue;
      if (resourceSchemaName === undefined) {
        throw new TypeError(`${operationId} has unknown resource ${JSON.stringify(rule.resource)}`);
      }
      const schemas = assertRecord(
        assertRecord(document.components, "components").schemas,
        "schemas",
      );
      const resourceSchema = assertRecord(schemas[resourceSchemaName], resourceSchemaName);
      const properties = assertRecord(
        resourceSchema.properties,
        `${resourceSchemaName}.properties`,
      );
      if (properties[rule[key]] === undefined) {
        throw new TypeError(
          `${operationId} has no ${rule[key]} field on resource ${rule.resource}`,
        );
      }
    }
    if (!Array.isArray(entry.operation.security) || entry.operation.security.length !== 2) {
      throw new TypeError(
        `${operationId} resource authorization requires exactly two security alternatives`,
      );
    }
    const securityRoles = entry.operation.security.map((requirementValue) => {
      const requirement = assertRecord(requirementValue, `${operationId} security requirement`);
      const bearerRoles = requirement.BearerAuth;
      if (
        Object.keys(requirement).length !== 1 ||
        !Array.isArray(bearerRoles) ||
        bearerRoles.length !== 1 ||
        typeof bearerRoles[0] !== "string"
      ) {
        throw new TypeError(
          `${operationId} security alternatives must be singleton BearerAuth requirements`,
        );
      }
      return bearerRoles[0];
    });
    if (
      securityRoles.length !== 2 ||
      !securityRoles.includes(roles.global) ||
      !securityRoles.includes(roles.domain)
    ) {
      throw new TypeError(
        `${operationId} authorization role pair does not match its security roles`,
      );
    }
  }
  return registry;
}

