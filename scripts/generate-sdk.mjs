export async function generateSdkArtifacts(openApiSource, webhookSource) {
  const document = parseOpenApi(openApiSource);
  const webhookDocument = parseWebhookContract(webhookSource);
  validateWebhookContract(webhookDocument);
  const operations = collectOperations(document);
  const schemas = Object.keys(
    assertRecord(assertRecord(document.components, "components").schemas, "schemas"),
  );
  if (operations.length !== EXPECTED_OPERATION_COUNT || schemas.length !== EXPECTED_SCHEMA_COUNT) {
    throw new TypeError(
      `Expected ${EXPECTED_OPERATION_COUNT} operations and ${EXPECTED_SCHEMA_COUNT} schemas; received ${operations.length} and ${schemas.length}`,
    );
  }
  const webhookCount = Object.keys(
    assertRecord(webhookDocument.webhooks, "Webhook definitions"),
  ).length;
  const webhookSchemaCount = Object.keys(
    assertRecord(
      assertRecord(webhookDocument.components, "Webhook components").schemas,
      "Webhook schemas",
    ),
  ).length;
  if (
    webhookCount !== EXPECTED_WEBHOOK_COUNT ||
    webhookSchemaCount !== EXPECTED_WEBHOOK_SCHEMA_COUNT
  ) {
    throw new TypeError(
      `Expected ${EXPECTED_WEBHOOK_COUNT} webhooks and ${EXPECTED_WEBHOOK_SCHEMA_COUNT} webhook schemas; received ${webhookCount} and ${webhookSchemaCount}`,
    );
  }
  const profile = createProfile(document);
  const profileDigest = digestJsonArtifact(profile);
  const webhookDigest = digestYamlArtifact(Buffer.from(webhookSource, "utf8"));
  const profileJson = `${JSON.stringify(profile, null, 2)}\n`;
  const prettierConfig = (await resolveConfig(resolve(repositoryRoot, ".prettierrc.json"))) ?? {};
  const typescriptArtifacts = await Promise.all(
    [
      [outputPaths.restTypes, generateRestTypes(document, operations)],
      [outputPaths.operations, generateOperations(document, operations)],
      [outputPaths.profileTypes, generateProfileTypes()],
      [outputPaths.webhookTypes, generateWebhookTypes(webhookDocument, webhookDigest)],
      [outputPaths.webhookValidators, generateWebhookValidators(webhookDocument)],
      [
        outputPaths.contractDigests,
        generateContractDigests(
          digestYamlArtifact(Buffer.from(openApiSource, "utf8")),
          webhookDigest,
          profileDigest,
        ),
      ],
    ].map(async ([path, source]) => [
      path,
      await format(source, { ...prettierConfig, filepath: resolve(repositoryRoot, path) }),
    ]),
  );
  return new Map([
    ...typescriptArtifacts,
    [outputPaths.profileJson, profileJson],
    [outputPaths.profileDigest, `${profileDigest}\n`],
  ]);
}

async function run(check) {
  const openApiSource = await readFile(resolve(repositoryRoot, "openapi.yaml"), "utf8");
  const webhookSource = await readFile(resolve(repositoryRoot, "webhooks.yaml"), "utf8");
  const artifacts = await generateSdkArtifacts(openApiSource, webhookSource);
  const drift = [];
  for (const [path, expected] of artifacts) {
    const absolutePath = resolve(repositoryRoot, path);
    if (check) {
      let actual;
      try {
        actual = await readFile(absolutePath, "utf8");
      } catch (error) {
        if (error !== null && typeof error === "object" && error.code === "ENOENT")
          actual = undefined;
        else throw error;
      }
      if (actual !== expected) drift.push(path);
    } else {
      await mkdir(dirname(absolutePath), { recursive: true });
      await writeFile(absolutePath, expected, "utf8");
    }
  }
  if (drift.length > 0) {
    throw new TypeError(`Generated SDK artifacts are stale: ${drift.join(", ")}`);
  }
}

async function main() {
  const arguments_ = process.argv.slice(2);
  if (arguments_.some((argument) => argument !== "--check") || arguments_.length > 1) {
    throw new TypeError("Usage: node scripts/generate-sdk.mjs [--check]");
  }
  await run(arguments_[0] === "--check");
}

